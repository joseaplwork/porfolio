#!/usr/bin/env node

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = process.cwd();
const FEATURES_DIR = path.join(ROOT, 'src/features');
const APP_DIR = path.join(ROOT, 'src/app');
const OUTPUT_FILE = path.join(ROOT, 'docs/ai/context-index.generated.md');

function listDirectories(dirPath) {
  return readdirSync(dirPath)
    .filter((entry) => statSync(path.join(dirPath, entry)).isDirectory())
    .sort((a, b) => a.localeCompare(b));
}

function walkFiles(dirPath) {
  const entries = readdirSync(dirPath);
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry);
    const stats = statSync(fullPath);

    if (stats.isDirectory()) {
      files.push(...walkFiles(fullPath));
      continue;
    }

    files.push(fullPath);
  }

  return files;
}

function parseNamedExports(filePath) {
  const content = readFileSync(filePath, 'utf8');
  const exports = new Set();

  for (const match of content.matchAll(/export\s+(?:type\s+)?\{([^}]+)\}/g)) {
    const entries = match[1].split(',').map((entry) => entry.trim());
    for (const entry of entries) {
      if (!entry) continue;
      const aliasParts = entry.split(/\s+as\s+/i);
      exports.add(aliasParts[aliasParts.length - 1].trim());
    }
  }

  for (const match of content.matchAll(
    /export\s+(?:interface|type|const|function|class)\s+([A-Za-z0-9_]+)/g,
  )) {
    exports.add(match[1]);
  }

  return [...exports].sort((a, b) => a.localeCompare(b));
}

function parseDependencies(featureDir) {
  const files = walkFiles(featureDir).filter((filePath) =>
    ['.ts', '.tsx', '.mjs'].includes(path.extname(filePath)),
  );

  const dependencies = new Set();

  for (const filePath of files) {
    if (filePath.includes(`${path.sep}tests${path.sep}`)) {
      continue;
    }

    const content = readFileSync(filePath, 'utf8');
    for (const match of content.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
      const specifier = match[1];
      if (specifier.startsWith('.')) {
        continue;
      }
      dependencies.add(specifier);
    }
  }

  return [...dependencies].sort((a, b) => a.localeCompare(b));
}

function normalizeRoutePath(appFilePath) {
  const relative = path
    .relative(APP_DIR, appFilePath)
    .replaceAll(path.sep, '/')
    .replace(/\.(ts|tsx)$/, '');

  if (relative === 'page') {
    return '/';
  }

  const cleanSegments = relative
    .split('/')
    .filter((segment) => segment.length > 0)
    .filter((segment) => !(segment.startsWith('(') && segment.endsWith(')')))
    .filter((segment) => !['page', 'layout', 'loading', 'route'].includes(segment));

  if (cleanSegments.length === 0) {
    return '/';
  }

  return `/${cleanSegments.join('/')}`;
}

function parseRouteOwnership(featureName) {
  const appFiles = walkFiles(APP_DIR).filter((filePath) =>
    ['.ts', '.tsx'].includes(path.extname(filePath)),
  );
  const featureImportPrefix = `@/features/${featureName}`;

  const routes = [];

  for (const appFilePath of appFiles) {
    const content = readFileSync(appFilePath, 'utf8');
    if (!content.includes(featureImportPrefix)) {
      continue;
    }

    routes.push({
      route: normalizeRoutePath(appFilePath),
      ownerFile: path.relative(ROOT, appFilePath).replaceAll(path.sep, '/'),
    });
  }

  return routes.sort((a, b) => a.route.localeCompare(b.route));
}

function generateMarkdown() {
  const featureNames = listDirectories(FEATURES_DIR);

  const lines = [
    '# AI Context Index (Generated)',
    '',
    'This file is auto-generated by `npm run context:update`.',
    'Do not edit manually.',
    '',
    '## Features',
    '',
  ];

  for (const featureName of featureNames) {
    const featureDir = path.join(FEATURES_DIR, featureName);
    const indexFile = path.join(featureDir, 'index.ts');
    const contractsFile = path.join(featureDir, 'contracts.ts');

    const indexExports = parseNamedExports(indexFile);
    const contractExports = parseNamedExports(contractsFile);
    const dependencies = parseDependencies(featureDir);
    const routes = parseRouteOwnership(featureName);

    lines.push(`### ${featureName}`);
    lines.push('');
    lines.push(
      `- Public API exports: ${indexExports.length > 0 ? indexExports.join(', ') : 'None'}`,
    );
    lines.push(
      `- Contract exports: ${contractExports.length > 0 ? contractExports.join(', ') : 'None'}`,
    );
    lines.push(
      `- Internal/external dependencies: ${dependencies.length > 0 ? dependencies.join(', ') : 'None'}`,
    );

    if (routes.length === 0) {
      lines.push('- Route ownership: None');
    } else {
      lines.push(
        `- Route ownership: ${routes
          .map((route) => `${route.route} (${route.ownerFile})`)
          .join(', ')}`,
      );
    }

    lines.push('');
  }

  return `${lines.join('\n')}`;
}

const markdown = generateMarkdown();

if (process.argv.includes('--stdout')) {
  process.stdout.write(markdown);
} else {
  writeFileSync(OUTPUT_FILE, markdown, 'utf8');
  console.log(`Generated ${path.relative(ROOT, OUTPUT_FILE)}`);
}
